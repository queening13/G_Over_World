const ATTR = { Beam: '빔', Physical: '실탄', Special: '특수' };

/* =========================== 변환 =========================================
   구 치환은 항상 "긴 키부터". 짧은 키가 먼저 걸려 반쪽만 번역되는 사고를 막는다. */
const byLenDesc = obj => Object.keys(obj).sort((a, b) => b.length - a.length).map(k => [k, obj[k]]);
const WEP_P = byLenDesc(WEP_PHRASE);
const AB_P = byLenDesc(AB_PHRASE);
const DET_T = byLenDesc(DET_TOKEN);
const SER_P = byLenDesc(SERIES);

export function trWeapon(s) {
  if (!s) return s;
  if (WEP_EXACT[s]) return WEP_EXACT[s];
  let t = s;
  t = t.replace(/(\d+)-(Barrel|Tube|Shot)\b/gi, '$1연장');   /* 5-Barrel → 5연장 */
  t = t.replace(/\bType ([A-Z]\d*|\d+[A-Z]?)\b/g, '$1형');    /* Type A2·Type 71·Type E → A2형·71형·E형 */
  for (const [en, ko] of WEP_P) t = t.split(en).join(ko);
  /* 남은 낱말만 치환. 괄호·슬래시는 구분자로 두어 '(Diffuse)' 같은 것도 걸리게 한다.
     하이픈은 구분자로 쓰지 않는다 — 'Air-to-Air' 가 쪼개지면 '공-to-공' 이 된다. */
  t = t.split(/([ ()/])/).map(tok => WEP_TOKEN[tok] || tok).join('');
  /* 안전망 : 'Funnels' 처럼 복수형 s 만 남는 경우를 정리한다 ('핀 판넬s' → '핀 판넬') */
  t = t.replace(/([가-힣])s\b/g, '$1');
  return t.replace(/\s{2,}/g, ' ').trim();
}

export function trAbilityName(s) {
  if (!s) return s;
  let t = s;
  for (const [en, ko] of SER_P) t = t.split(en).join(ko);
  for (const [en, ko] of AB_P) t = t.split(en).join(ko);
  return t.replace(/\bLV\s*(\d+)/gi, 'LV$1').replace(/\s{2,}/g, ' ').trim();
}

export function trAbilityDetail(s) {
  if (!s) return s;
  const one = s.replace(/\s*\n\s*/g, ' ').replace(/\s{2,}/g, ' ').trim();
  if (DET_EXACT[one]) return DET_EXACT[one];
  let t = one;
  for (const [re, ko] of DET_CLAUSE) t = t.replace(re, ko);
  for (const [en, ko] of DET_T) t = t.split(en).join(ko);
  t = t.replace(/\b[Ii]ncrease ([^.]+?) by (\d+)%/g, '$1 $2% 증가')
       .replace(/\b[Rr]educe ([^.]+?) by (\d+)%/g, '$1 $2% 감소')
       .replace(/\b[Rr]estore ([^.]+?) (\d+)%/g, '$1 $2% 회복')
       .replace(/\b[Ii]ncrease ([^.]+?) by (\d+)\b/g, '$1 $2 증가')
       .replace(/\band\b/g, '·');
  return t.replace(/\s{2,}/g, ' ').replace(/\s+\./g, '.').trim();
}

export const trSeries = s => SERIES[s] || s;
export const trAttr = s => !s ? s : s.split('/').map(x => ATTR[x.trim()] || x.trim()).join('/');
